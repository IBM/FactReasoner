"""LCS as a function of Lambda: the closed form, checked on every rung, and the paper's figure.

For a committed world with prior probability u0 = pi(x*) (u0 = 2^-n with flat priors) and
Lambda = log P_R(x*) - log u0,

    LCS = e^Lambda (1 - u0) / (1 + e^Lambda (1 - 2 u0)),   Lambda in (-inf, -log u0].

This script asserts that closed form against the scorer (arr_coherence_eval.odds_lcs) on every
rung of the LoCoBench test split, gold graphs and the GPT-6 graph miner's graphs, and writes

* docs/arr2027/coherence/figures/fig_lcs_lambda.pdf  -- (a) the map for n = 2, 5, 14 and its
  u0 -> 0 limit sigma(Lambda); (b) every rung as (Lambda, LCS), with marginal rugs;
* docs/arr2027/coherence/numbers_lcslambda.tex       -- macros (prefix \\lcl).

    uv run --with matplotlib --with numpy python scripts/arr_lcs_lambda.py
"""

from __future__ import annotations

import math
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "src"))
sys.path.insert(0, os.path.join(REPO, "scripts"))

import arr_coherence_eval as A  # noqa: E402
import arr_slot3_eval as E  # noqa: E402

E.DATA = os.path.join(REPO, "data", "locobench-slot3-test")
E.ROOT = os.path.join(REPO, "results", "arr2027_slot3_test")
FIG = os.path.join(REPO, "docs", "arr2027", "coherence", "figures", "fig_lcs_lambda.pdf")
MACROS = os.path.join(REPO, "docs", "arr2027", "coherence", "numbers_lcslambda.tex")
RAMP = ("#86b6ef", "#2a78d6", "#104281")      # validated ordinal ramp: n = 2, 5, 14
GOLD, MINED = "#2a78d6", "#eb6834"             # validated categorical pair
INK, MUTED, GRID = "#52514E", "#898781", "#E4E2DD"


def lcs_closed(lam: float, u0: float) -> float:
    """The closed form, written to stay finite for very negative Lambda."""
    if lam > 0:
        e = math.exp(-lam)
        return (1 - u0) / (e + (1 - 2 * u0))
    e = math.exp(lam)
    return e * (1 - u0) / (1 + e * (1 - 2 * u0))


def lambda_of_lcs(lcs: float, u0: float) -> float:
    """The inverse map: Lambda = log LCS - log[(1 - LCS) - u0 (1 - 2 LCS)]."""
    return math.log(lcs) - math.log((1 - lcs) - u0 * (1 - 2 * lcs))


def rungs():
    items, fams, ladders = E.load()
    mined = E.mined_relations("graph_gpt6")
    ids = sorted({i for l in ladders for i in l["item_ids"]})
    out = {"gold": [], "graph_gpt6": []}
    for iid in ids:
        it = items[iid]
        for arm, rels in (("gold", E.gold_relations(it)), ("graph_gpt6", mined.get(iid))):
            if rels is None:
                continue
            s = E.score_item(it, rels)
            out[arm].append((s["lambda"], s["lcs"], s["n"]))
    return out


def main() -> int:
    data = rungs()
    # 1. the closed form against the scorer, on every rung
    worst = 0.0
    for arm, rows in data.items():
        for lam, lcs, n in rows:
            worst = max(worst, abs(lcs_closed(lam, 2.0 ** -n) - lcs))
    assert worst < 1e-12, worst
    # 2. the inverse round trip where LCS is not at machine precision of 0 or 1
    inv = max(abs(lambda_of_lcs(lcs, 2.0 ** -n) - lam) for rows in data.values()
              for lam, lcs, n in rows if 1e-9 < lcs < 1 - 1e-9)
    # 3. macros
    digits = "Zero One Two Three Four Five Six Seven Eight Nine".split()
    L = ["% Generated by scripts/arr_lcs_lambda.py -- do not edit by hand."]

    def sci(x):
        e = int(math.floor(math.log10(x)))
        return f"{x / 10 ** e:.0f}\\times10^{{{e}}}"

    def m(name, val):
        name = "".join(digits[int(c)] if c.isdigit() else c for c in name)
        L.append(f"\\newcommand{{\\lcl{name}}}{{{val}}}")

    for arm, tag in (("gold", "Gold"), ("graph_gpt6", "Gpt")):
        rows = data[arm]
        lams = [r[0] for r in rows]
        m(f"N{tag}", f"{len(rows):,}".replace(",", "{,}"))
        m(f"LamMin{tag}", f"{min(lams):.1f}")
        m(f"LamMax{tag}", f"{max(lams):.2f}")
        m(f"Low{tag}", f"{100 * sum(r[1] < 0.01 for r in rows) / len(rows):.0f}")
        m(f"High{tag}", f"{100 * sum(r[1] > 0.99 for r in rows) / len(rows):.0f}")
    ns = sorted({r[2] for rows in data.values() for r in rows})
    m("NMin", ns[0])
    m("NMax", ns[-1])
    m("LamCapMin", f"{ns[0] * math.log(2):.2f}")
    m("LamCapMax", f"{ns[-1] * math.log(2):.2f}")
    sig = lambda v: 1 / (1 + math.exp(-v)) if v >= 0 else math.exp(v) / (1 + math.exp(v))  # noqa: E731
    dev = max(abs(r[1] - sig(r[0])) for rows in data.values() for r in rows)
    m("MaxDevSigma", sci(dev))
    m("CheckErr", sci(worst))
    m("InvErr", sci(inv))
    os.makedirs(os.path.dirname(MACROS), exist_ok=True)
    open(MACROS, "w").write("\n".join(L) + "\n")
    # 4. figure
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np

    plt.rcParams.update({"font.family": "serif", "font.size": 7.5, "axes.edgecolor": MUTED,
                         "axes.labelcolor": INK, "xtick.color": INK, "ytick.color": INK,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "axes.linewidth": 0.6})
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.45), constrained_layout=True,
                             gridspec_kw={"width_ratios": [1.0, 1.25]})
    ax = axes[0]
    x = np.linspace(-8, 10.5, 600)
    ax.plot(x, 1 / (1 + np.exp(-x)), color=MUTED, lw=1.2, ls=(0, (4, 3)), zorder=2,
            label=r"$\sigma(\Lambda)$, the limit $u_0\to0$")
    for n, col in zip((2, 5, 14), RAMP):
        cap = n * math.log(2)
        xs = x[x <= cap]
        ax.plot(xs, [lcs_closed(v, 2.0 ** -n) for v in xs], color=col, lw=2, zorder=3,
                label=f"$n={n}$")
        ax.scatter([cap], [1.0], s=16, color=col, zorder=4, edgecolor="white", linewidth=0.8)
    ax.axhline(0.5, color=GRID, lw=0.8, zorder=1)
    ax.axvline(0, color=GRID, lw=0.8, zorder=1)
    ax.set_xlim(-8, 10.6)
    ax.set_ylim(-0.02, 1.04)
    ax.set_xlabel(r"$\Lambda$ (nats)")
    ax.set_ylabel(r"$\mathrm{LCS}$")
    ax.set_title(r"(a) the map, flat priors ($u_0=2^{-n}$)", fontsize=7.5, color=INK, loc="left")
    ax.legend(fontsize=6.2, frameon=False, loc="upper left", handlelength=1.6)
    ax.text(10.4, 0.06, "dots: the cap\n$\\Lambda=n\\log 2$", ha="right", fontsize=6, color=MUTED)

    ax = axes[1]
    lo = -10.0
    for arm, col, lab in (("gold", GOLD, "gold graphs"), ("graph_gpt6", MINED, "graph-level miner, GPT-6")):
        rows = data[arm]
        lam = np.array([max(r[0], lo) for r in rows])
        lcs = np.array([r[1] for r in rows])
        ax.scatter(lam, lcs, s=6, color=col, alpha=0.55, lw=0, zorder=3, label=lab)
        off = 0 if arm == "gold" else 1
        ax.plot(lam, np.full_like(lam, -0.05 - 0.025 * off), "|", color=col, ms=4, alpha=0.35,
                zorder=2)
        ax.plot(np.full_like(lcs, lo - 0.6 - 0.45 * off), lcs, "_", color=col, ms=4, alpha=0.35,
                zorder=2)
    xs = np.linspace(lo, 14 * math.log(2), 400)
    for n in (12, 14):
        ax.plot(xs[xs <= n * math.log(2)], [lcs_closed(v, 2.0 ** -n) for v in xs
                                             if v <= n * math.log(2)],
                color=INK, lw=0.7, zorder=4)
    ax.axhline(0.5, color=GRID, lw=0.8, zorder=1)
    ax.axvline(0, color=GRID, lw=0.8, zorder=1)
    ax.set_xlim(lo - 1.6, 10.6)
    ax.set_ylim(-0.1, 1.04)
    ax.set_xlabel(r"$\Lambda$ (nats)")
    ax.set_title("(b) every response of the test split, both scales", fontsize=7.5, color=INK,
                 loc="left")
    ax.legend(fontsize=6.2, frameon=False, loc="lower right", markerscale=2.2, handletextpad=0.3,
              bbox_to_anchor=(1.0, 0.08))
    ax.text(-9.0, 0.97, "curves: $n=12$, $14$\nrugs: each scale's distribution",
            ha="left", va="top", fontsize=6, color=MUTED)
    fig.savefig(FIG)
    print(f"checked {sum(len(v) for v in data.values())} rungs (max |closed - scorer| = "
          f"{worst:.1e}; inverse {inv:.1e}); wrote {FIG} and {MACROS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
