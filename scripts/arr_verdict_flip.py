"""Sensitivity of LCS to a single wrong verdict (coherence paper, review m12).

On LoCoBench's gold graphs (test split, flat priors), flip the verdict of one claim at a time
and record how far LCS moves, how many of the response's relations change sign, and how the
move grows with the claim's degree in the relation graph. A claim no relation touches cannot
change any sign, and under flat priors u0 = pi(x*) = 2^-n does not change either, so its flip
leaves LCS unchanged; this is checked (``untouched_max_abs``).

    .venv/bin/python scripts/arr_verdict_flip.py --macros docs/arr2027/coherence/numbers_flip.tex
"""

from __future__ import annotations

import argparse
import os
import statistics as st
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "scripts"))
sys.path.insert(0, os.path.join(REPO, "src"))

import arr_coherence_eval as A  # noqa: E402
import arr_slot3_eval as E  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--macros", default=None)
    args = ap.parse_args()
    E.DATA = os.path.join(REPO, "data", "locobench-slot3-test")
    items, _fams, _ladders = E.load()
    rows = []
    for iid, it in items.items():
        rels = E.gold_relations(it)
        atoms = sorted(it["atoms"], key=lambda a: a["pos"])
        n = len(atoms)
        xv = np.array([1 if a["factual"] else 0 for a in atoms])
        tup = [(E._idx(r["source"]), E._idx(r["target"]), r["type"], float(r["probability"]))
               for r in rels]
        pu = np.full(n, 0.5)
        base = A.lcs_flat(A.confirmation(pu, tup, xv), n)
        for i in range(n):
            x = xv.copy()
            x[i] = 1 - x[i]
            deg = sum(i in (s, t) for s, t, _ty, _p in tup)
            flips = sum(A.is_support(r, xv) != A.is_support(r, x) for r in tup)
            lcs = A.lcs_flat(A.confirmation(pu, tup, x), n)
            rows.append({"deg": deg, "flips": flips, "d": lcs - base, "was_true": int(xv[i])})
    touched = [r for r in rows if r["deg"] > 0]
    ad = lambda R: [abs(r["d"]) for r in R]  # noqa: E731
    out = {
        "flips": len(rows),
        "touched": len(touched),
        "untouched_max_abs": max(ad([r for r in rows if r["deg"] == 0]) or [0.0]),
        "median_abs": st.median(ad(touched)),
        "p90_abs": float(np.quantile(ad(touched), 0.9)),
        "max_abs": max(ad(touched)),
        "share_sign_change": sum(r["flips"] > 0 for r in touched) / len(touched),
        "share_over_tenth": sum(abs(r["d"]) > 0.1 for r in touched) / len(touched),
        "by_degree": {k: st.median(ad([r for r in touched if min(r["deg"], 3) == k]))
                      for k in (1, 2, 3) if any(min(r["deg"], 3) == k for r in touched)},
    }
    for k, v in out.items():
        print(f"{k:22s} {v}")
    if args.macros:
        L = ["% Generated by scripts/arr_verdict_flip.py -- do not edit by hand."]
        m = lambda name, val: L.append(f"\\newcommand{{\\flip{name}}}{{{val}}}")  # noqa: E731
        m("N", f"{out['flips']:,}".replace(",", "{,}"))
        m("Touched", f"{out['touched']:,}".replace(",", "{,}"))
        m("UntouchedMax", f"{out['untouched_max_abs']:.0e}" if out["untouched_max_abs"] else "0")
        m("Median", f"{out['median_abs']:.3f}")
        m("PNinety", f"{out['p90_abs']:.2f}")
        m("Max", f"{out['max_abs']:.2f}")
        m("SignChange", f"{100 * out['share_sign_change']:.0f}")
        m("OverTenth", f"{100 * out['share_over_tenth']:.0f}")
        for k, name in ((1, "One"), (2, "Two"), (3, "Three")):
            if k in out["by_degree"]:
                m(f"Deg{name}", f"{out['by_degree'][k]:.3f}")
        open(args.macros, "w").write("\n".join(L) + "\n")
        print(f"wrote {args.macros}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
