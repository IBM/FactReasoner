"""Phase C of the second review of the coherence paper: the non-sequitur control (C4).

``judge``  The pairwise GPT-6 judge given the claims, their verdicts and the paper's definition
           (scripts/run_fair_judges.py, PAIRWISE_V) compares each unedited response with its
           non-sequitur version, in both orders.
``eval``   On the GPT-6 graph-level mines of data/ext/loco-nonseq (both versions mined in one run):
           how often the miner extracts the planted inference, how often LCS and the signed sum
           rise, and which version the judge prefers.

    LOCOBENCH_NO_CACHE=1 .venv/bin/python scripts/arr_phasec.py judge
    .venv/bin/python scripts/arr_phasec.py eval --macros docs/arr2027/coherence/numbers_nonseq.tex
"""

from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "scripts"))
sys.path.insert(0, os.path.join(REPO, "src"))

import arr_coherence_eval as A  # noqa: E402
import ext_eval as X  # noqa: E402
import run_fair_judges as F  # noqa: E402

DS = "loco-nonseq"
OUT = os.path.join(REPO, "results", "ext", DS)


VARIANTS = ("nonseq", "valid")


def pairs(kind="nonseq"):
    it = X.items(DS)
    by = {}
    for iid, x in it.items():
        by.setdefault(x["expected"]["orig_item"], {})[x["expected"]["check"]] = x
    return [(v["nonseq_orig"], v[kind]) for v in by.values() if "nonseq_orig" in v and kind in v]


def cmd_judge(args):
    gen = F.make_generate(args.model)
    jobs = []
    for kind in VARIANTS:
        for o, n in pairs(kind):
            for order in ("on", "no"):
                jobs.append({"key": [o["expected"]["orig_item"], kind, order], "o": o, "n": n,
                             "order": order})

    def worker(job):
        a, b = (job["o"], job["n"]) if job["order"] == "on" else (job["n"], job["o"])
        text = gen(F.PAIRWISE_V.format(construct=F.CONSTRUCT, claims=F.claims_block(job["o"]),
                                       a=a["response"].strip(), b=b["response"].strip()))
        m = F._CHOICE.findall(text)
        return {"key": job["key"], "ok": bool(m), "choice": m[-1] if m else None, "tail": text[-300:]}

    F.run_jobs(jobs, os.path.join(OUT, f"judge_pairwise_verdicts__{args.model}.jsonl"), worker,
               args.workers)
    return 0


def cmd_eval(args):
    allres = {kind: eval_kind(kind) for kind in VARIANTS}
    print(json.dumps(allres, indent=1))
    if args.macros:
        L = ["% Generated by scripts/arr_phasec.py eval -- do not edit by hand."]
        pct = lambda a, b: f"{100 * a / b:.0f}" if b else "--"  # noqa: E731
        for kind, res in allres.items():
            t = {"nonseq": "ns", "valid": "nv"}[kind]
            n = res["pairs"]
            L += [f"\\newcommand{{\\{t}Pairs}}{{{n}}}",
                  f"\\newcommand{{\\{t}Extracted}}{{{pct(res['extracted'], n)}}}",
                  f"\\newcommand{{\\{t}LcsRise}}{{{pct(res['lcs_rise'], n)}}}",
                  f"\\newcommand{{\\{t}LcsFall}}{{{pct(res['lcs_fall'], n)}}}",
                  f"\\newcommand{{\\{t}WsumRise}}{{{pct(res['wsum_rise'], n)}}}",
                  f"\\newcommand{{\\{t}LcsRiseExtracted}}{{{pct(res['lcs_rise_extracted'], res['extracted_n'])}}}"]
            if "judge_pairs" in res:
                jn = res["judge_pairs"]
                L += [f"\\newcommand{{\\{t}JudgePairs}}{{{jn}}}",
                      f"\\newcommand{{\\{t}JudgeEdited}}{{{pct(res['judge_prefers_edited'], jn)}}}",
                      f"\\newcommand{{\\{t}JudgeOrig}}{{{pct(res['judge_prefers_orig'], jn)}}}",
                      f"\\newcommand{{\\{t}JudgeTie}}{{{pct(res['judge_tie'], jn)}}}"]
        open(args.macros, "w").write("\n".join(L) + "\n")
        print(f"wrote {args.macros}")
    return 0


def eval_kind(kind):
    recs, err = X.records(DS, "graph_gpt6")
    res = {"pairs": 0, "extracted": 0, "lcs_rise": 0, "lcs_fall": 0, "wsum_rise": 0, "wsum_fall": 0,
           "lcs_rise_extracted": 0, "extracted_n": 0, "errors": err}
    for o, n in pairs(kind):
        if o["id"] not in recs or n["id"] not in recs:
            continue
        s, t = int(n["expected"]["premise_atom"][1:]), int(n["expected"]["conclusion_atom"][1:])
        ro, rn = X.rels_of(recs[o["id"]]), X.rels_of(recs[n["id"]])
        x = np.array([1 if a["factual"] else 0 for a in sorted(n["atoms"], key=lambda a: a["pos"])])
        planted = any({r[0], r[1]} == {s, t} for r in rn) and not any({r[0], r[1]} == {s, t} for r in ro)
        k = n["num_atoms"]
        lo = A.lcs_flat(A.confirmation(np.full(k, 0.5), ro, x), k)
        ln = A.lcs_flat(A.confirmation(np.full(k, 0.5), rn, x), k)
        wo, wn = X.signed_sum(k, ro, list(x)), X.signed_sum(k, rn, list(x))
        res["pairs"] += 1
        res["extracted"] += planted
        res["lcs_rise"] += ln > lo + X.TIE
        res["lcs_fall"] += ln < lo - X.TIE
        res["wsum_rise"] += wn > wo + X.TIE
        res["wsum_fall"] += wn < wo - X.TIE
        if planted:
            res["extracted_n"] += 1
            res["lcs_rise_extracted"] += ln > lo + X.TIE
    jp = os.path.join(OUT, "judge_pairwise_verdicts__gpt-6-sol.jsonl")
    if os.path.exists(jp):
        votes = {}
        for r in F.jsonl(jp):
            if not r.get("ok"):
                continue
            oid, k_, order = r["key"]
            if k_ != kind:
                continue
            edited = "B" if order == "on" else "A"
            v = 0 if r["choice"] == "=" else (1 if r["choice"] == edited else -1)
            votes.setdefault(oid, []).append(v)
        net = [sum(v) for v in votes.values() if len(v) == 2]
        res["judge_pairs"] = len(net)
        res["judge_prefers_edited"] = sum(v > 0 for v in net)
        res["judge_prefers_orig"] = sum(v < 0 for v in net)
        res["judge_tie"] = sum(v == 0 for v in net)
    return res


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    j = sub.add_parser("judge")
    j.add_argument("--model", default="gpt-6-sol")
    j.add_argument("--workers", type=int, default=8)
    e = sub.add_parser("eval")
    e.add_argument("--macros", default=None)
    args = ap.parse_args()
    return {"judge": cmd_judge, "eval": cmd_eval}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
