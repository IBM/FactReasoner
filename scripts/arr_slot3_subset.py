"""LoCoBench with a miner from outside the generator and committee (review Phase 3.5).

The graph-level miner with Llama-3.3-70B ran on a stratified subset of the test split (12 families
per primary ladder type, results/arr2027_slot3_test/arms/graph_llama_subset_families.txt). This
script compares it with the GPT-6 graph-level arm on exactly the same ladders: LCS and the signed
weight sum on increases and invariances, falls, and pair-level extraction F1 against gold.

    .venv/bin/python scripts/arr_slot3_subset.py --macros docs/arr2027/coherence/numbers_subset.tex
"""

from __future__ import annotations

import argparse
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "scripts"))
sys.path.insert(0, os.path.join(REPO, "src"))

import arr_slot3_eval as E  # noqa: E402

ROOT = os.path.join(REPO, "results", "arr2027_slot3_test")
ARMS = {"graph_gpt6": "Gpt", "graph_llama": "Llama"}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--macros", default=None)
    args = ap.parse_args()
    E.DATA = os.path.join(REPO, "data", "locobench-slot3-test")
    E.ROOT = ROOT
    items, _fams, ladders = E.load()
    fams = {l.strip() for l in open(os.path.join(ROOT, "arms", "graph_llama_subset_families.txt"))
            if l.strip()}
    mined = {arm: E.mined_relations(arm) for arm in ARMS}
    have = set(mined["graph_llama"]) & set(mined["graph_gpt6"])
    sub = [l for l in ladders if l["family_id"] in fams and all(i in have for i in l["item_ids"])]
    out = {"ladders": len(sub), "families": len({l["family_id"] for l in sub})}
    for arm, tag in ARMS.items():
        sc = {iid: E.score_item(items[iid], rels) for iid, rels in mined[arm].items() if iid in have}
        for key, kt in (("lcs", "Lcs"), ("wsum", "Wsum")):
            r = E.assess(sub, lambda i, sc=sc, key=key: sc[i][key] if i in sc else None,
                         E.REL_TIE, rel=True)
            prs = E.pair_rows(sub, lambda i, sc=sc, key=key: sc[i][key] if i in sc else None,
                              E.REL_TIE, rel=True)
            inc = [p for p in prs if p["type"] in E.INCREASE]
            out[f"{tag}{kt}"] = {"inc": r.get("inc"), "inv": r.get("inv"),
                                 "chain": r.get("pair_CHAIN"),
                                 "falls": (sum(not p["ok"] and not p["tie"] for p in inc), len(inc))}
        ex = E.extraction(items, {i: mined[arm][i] for i in have
                                  if items[i]["expected"]["family_id"] in fams})
        out[f"{tag}PairF"] = ex["pair"][2]
        out[f"{tag}CoupF"] = ex["coupling"][2]
    for k, v in out.items():
        print(k, v)
    if args.macros:
        L = ["% Generated by scripts/arr_slot3_subset.py -- do not edit by hand."]
        m = lambda name, val: L.append(f"\\newcommand{{\\sub{name}}}{{{val}}}")  # noqa: E731
        pct = lambda t: f"{100 * t[0] / t[1]:.0f}" if t and t[1] else "--"  # noqa: E731
        m("Ladders", out["ladders"])
        m("Families", out["families"])
        for tag in ARMS.values():
            for kt in ("Lcs", "Wsum"):
                d = out[f"{tag}{kt}"]
                m(f"{tag}{kt}Inc", pct(d["inc"]))
                m(f"{tag}{kt}Inv", pct(d["inv"]))
                m(f"{tag}{kt}Chain", pct(d["chain"]))
                m(f"{tag}{kt}Falls", pct(d["falls"]))
                m(f"{tag}{kt}NInc", d["inc"][1] if d["inc"] else 0)
            m(f"{tag}PairF", f"{out[f'{tag}PairF']:.2f}")
            m(f"{tag}CoupF", f"{out[f'{tag}CoupF']:.2f}")
        open(args.macros, "w").write("\n".join(L) + "\n")
        print(f"wrote {args.macros}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
