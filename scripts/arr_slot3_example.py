"""One SIGN ladder end to end, for the ARR coherence paper's worked example (appendix).

Prints, for candidate SIGN ladders of the test split, the sentences that differ between the
three rungs, the two slot claims with their factuality labels, and every score per rung:
LCS (verdict and asserted world) on gold graphs, LCS on the GPT-6
graph-level miner's graphs, the two GPT-6 judges and length. ``--ladder f123-SIGN`` prints one
ladder only; ``--tex PATH`` writes that ladder's table for the paper.

    .venv/bin/python scripts/arr_slot3_example.py --ladder f003-SIGN \\
        --tex docs/arr2027/coherence/example_sign.tex
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import arr_slot3_eval as E  # noqa: E402

E.DATA, E.ROOT = "data/locobench-slot3-test", "results/arr2027_slot3_test"
BASE = {"judge_geval@gpt-6-sol": "G-Eval", "judge_direct@gpt-6-sol": "rating",
        "control_length": "length"}


def sentences(t):
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", t) if s.strip()]


def edited(texts):
    """The sentences of each rung that are not shared by all three."""
    shared = set(sentences(texts[0])) & set(sentences(texts[1])) & set(sentences(texts[2]))
    return [[s for s in sentences(t) if s not in shared] for t in texts]


RUNG = ["$\\rho_0$: derives the falsehood", "$\\rho_1$: no link",
        "$\\rho_2$: refutes the falsehood"]


def _tex(t):
    t = re.sub(r'"([^"]*)"', r"``\1''", t)
    return (t.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")
            .replace("_", "\\_").replace("#", "\\#").replace("$", "\\$"))


def _order(v):
    if any(x is None for x in v):
        return "---"
    if v[0] < v[1] < v[2]:
        return "as declared"
    if v[0] == v[1] == v[2]:
        return "no change"
    if v[0] > v[1] > v[2]:
        return "reversed"
    return "partly"


def slot_claims(items, ids):
    """The (true, false) claim texts the SIGN slot joins: the endpoints of the relation whose
    filler differs between the derive and refute rungs."""
    def slot(it):
        return {(r["source_id"], r["target_id"]): r.get("filler")
                for r in it["relations"] if r.get("slot_id")}
    a, c = slot(items[ids[0]]), slot(items[ids[2]])
    pair = next(k for k in a if a.get(k) != c.get(k))
    atoms = {x["id"]: x for x in items[ids[0]]["atoms"]}
    ends = sorted((atoms[i] for i in pair), key=lambda x: not x["factual"])
    return [x["text"] for x in ends]


def write_tex(path, lad, sents, rows, framing, claims, words):
    L = ["% Generated by scripts/arr_slot3_example.py -- do not edit by hand.",
         "\\begin{table*}[t]", "\\centering\\small", "\\setlength{\\tabcolsep}{4pt}",
         "\\begin{tabular}{@{}p{3.3cm}p{11.7cm}@{}}", "\\toprule",
         "\\multicolumn{2}{@{}p{15.4cm}@{}}{\\emph{Question:} " + _tex(framing) + "} \\\\",
         "\\midrule", "Rung & The sentences that differ between the rungs \\\\", "\\midrule"]
    for k, ss in enumerate(sents):
        L.append(RUNG[k] + " & " + _tex(" ".join(ss)) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "", "\\vspace{4pt}",
          "\\begin{tabular}{@{}lcccl@{}}", "\\toprule",
          "Score & $\\rho_0$ & $\\rho_1$ & $\\rho_2$ & order \\\\", "\\midrule"]
    for k, v in rows.items():
        cells = " & ".join("---" if x is None else f"{x:.3f}" for x in v)
        name = {"LCS, gold": "$\\LCS$, gold graph (ours)",
                "LCS, GPT-6 graphs": "$\\LCS$, GPT-6 graph-level miner (ours)",
                "LCS asserted, gold": "$\\LCS$ at the asserted world, gold graph",
                "G-Eval": "G-Eval judge, GPT-6", "rating": "1--5 rating judge, GPT-6",
                "length": "response length"}[k]
        L.append(f"{name} & {cells} & {_order(v)} \\\\")
    L += ["\\bottomrule", "\\end{tabular}",
          "\\caption{One \\cp{sign} ladder of the test split (" + lad["ladder_id"].split("-")[0]
          + "), end to end. The slot joins a true claim (``" + _tex(claims[0]) + "'') and a false "
          "one (``" + _tex(claims[1]) + "''). The three rungs share every other sentence of the "
          f"{words}-word answer, every claim and every verdict; only the link between the two "
          "claims changes. "
          "Judges are means of five runs mapped to $[0,1]$; length is normalized.}",
          "\\label{tab:example}", "\\end{table*}"]
    open(path, "w").write("\n".join(L) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ladder")
    ap.add_argument("--tex", help="Write the (single) ladder's LaTeX table here.")
    args = ap.parse_args()
    items, fams, ladders = E.load()
    mined = E.mined_relations("graph_gpt6")
    base = {}
    for p in glob.glob(os.path.join(E.ROOT, "baselines", "*.jsonl")):
        for line in open(p):
            r = json.loads(line)
            if r["name"] in BASE and r.get("score") is not None:
                base[(r["name"], r["item_id"])] = r["score"]
    for lad in ladders:
        if lad["type"] != "SIGN" or (args.ladder and lad["ladder_id"] != args.ladder):
            continue
        ids = lad["item_ids"]
        g = [E.score_item(items[i], E.gold_relations(items[i])) for i in ids]
        m = [E.score_item(items[i], mined[i]) if i in mined else None for i in ids]
        b = {n: [base.get((n, i)) for i in ids] for n in BASE}
        rows = {
            "LCS, gold": [x["lcs"] for x in g],
            "LCS asserted, gold": [x["lcs_assert"] for x in g],
            "LCS, GPT-6 graphs": [x["lcs"] if x else None for x in m],
            **{BASE[n]: v for n, v in b.items()},
        }
        if args.tex:
            write_tex(args.tex, lad, edited([items[i]["response"] for i in ids]), rows,
                      items[ids[0]]["meta"]["framing"], slot_claims(items, ids),
                      items[ids[1]]["meta"]["word_count"])
            continue
        print("=" * 100)
        print(lad["ladder_id"], items[ids[0]]["meta"]["framing"])
        for k, sents in enumerate(edited([items[i]["response"] for i in ids])):
            print(f"  rung {k}:", " | ".join(sents))
        for k, v in rows.items():
            print(f"  {k:22s}", "  ".join("  --- " if x is None else f"{x:6.3f}" for x in v))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
