"""Phase B of the second review of the coherence paper: re-analyses of existing LoCoBench records.

``noise``   The increasing ladders under injected verdict noise (review N15): each claim's verdict is
            flipped with probability q, the same flips for all three rungs of a ladder (they share
            their claims), and LCS and the signed weight sum are read on the GOLD graphs at the
            noisy committed world. Reported: the share of declared increases satisfied, by type.
``paired``  Paired family-cluster bootstrap intervals (review N1, N9, N12): the difference between
            two scores' satisfaction rates on the same rung pairs, resampling families.

    .venv/bin/python scripts/arr_phaseb.py noise --macros docs/arr2027/coherence/numbers_phaseb_noise.tex
    .venv/bin/python scripts/arr_phaseb.py paired --macros docs/arr2027/coherence/numbers_phaseb_paired.tex
"""

from __future__ import annotations

import argparse
import itertools
import json
import os
import random
import sys
from collections import defaultdict

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "scripts"))
sys.path.insert(0, os.path.join(REPO, "src"))

import arr_coherence_eval as A  # noqa: E402
import arr_slot3_eval as E  # noqa: E402

ROOT = os.path.join(REPO, "results", "arr2027_slot3_test")
SEED = 20261127
QS = (0.05, 0.10, 0.20)
DRAWS = 20
BOOT = 2000


def cmd_noise(args):
    E.DATA = os.path.join(REPO, "data", "locobench-slot3-test")
    items, _f, ladders = E.load()
    inc = [l for l in ladders if l["type"] in E.INCREASE]
    rng = np.random.default_rng(SEED)
    res = {}
    for q in QS:
        c = defaultdict(lambda: [0, 0])
        fam = defaultdict(lambda: defaultdict(list))  # type -> family -> [(lcs ok, wsum ok)]
        for lad in inc:
            its = [items[i] for i in lad["item_ids"]]
            atoms = [sorted(it["atoms"], key=lambda a: a["pos"]) for it in its]
            n = len(atoms[0])
            xv = np.array([1 if a["factual"] else 0 for a in atoms[0]])
            graphs = [[(E._idx(r["source"]), E._idx(r["target"]), r["type"], float(r["probability"]))
                       for r in E.gold_relations(it)] for it in its]
            for _ in range(DRAWS):
                x = np.where(rng.random(n) < q, 1 - xv, xv)
                lcs = [A.lcs_flat(A.confirmation(np.full(n, 0.5), g, x), n) for g in graphs]
                ws = [sum(p * (1 if A.is_support((s, t, ty, p), x) else -1) for s, t, ty, p in g)
                      for g in graphs]
                for i, j in itertools.combinations(range(3), 2):
                    okl = E.pair_ok(lad["type"], lcs[i], lcs[j], E.REL_TIE, True)
                    okw = E.pair_ok(lad["type"], ws[i], ws[j], E.REL_TIE, True)
                    for t in (lad["type"], "inc"):
                        fam[t][lad["family_id"]].append((float(okl), float(okw)))
                    for key, v in (("lcs", lcs), ("wsum", ws)):
                        ok = E.pair_ok(lad["type"], v[i], v[j], E.REL_TIE, True)
                        c[(key, lad["type"])][0] += ok
                        c[(key, lad["type"])][1] += 1
                        c[(key, "inc")][0] += ok
                        c[(key, "inc")][1] += 1
        res[q] = {f"{k[0]}:{k[1]}": v[0] / v[1] for k, v in c.items()}
        brng = random.Random(SEED)
        for t, F in fam.items():
            F = list(F.values())
            vals = []
            for _ in range(BOOT):
                smp = [brng.choice(F) for _ in F]
                tot = sum(len(f) for f in smp)
                vals.append(sum(a - b for f in smp for a, b in f) / tot)
            vals.sort()
            res[q][f"difflo:{t}"] = vals[int(0.025 * BOOT)]
            res[q][f"diffhi:{t}"] = vals[int(0.975 * BOOT) - 1]
        print(q, {k: round(v, 3) for k, v in res[q].items()})
    if args.macros:
        L = ["% Generated by scripts/arr_phaseb.py noise -- do not edit by hand."]
        for q, r in res.items():
            qt = {0.05: "Five", 0.10: "Ten", 0.20: "Twenty"}[q]
            for k, v in r.items():
                key, t = k.split(":")
                kt = {"lcs": "Lcs", "wsum": "Wsum", "difflo": "DiffLo", "diffhi": "DiffHi"}[key]
                val = f"{100 * v:+.1f}" if key.startswith("diff") else f"{100 * v:.0f}"
                L.append(f"\\newcommand{{\\vn{kt}{t.title()}{qt}}}{{{val}}}")
        open(args.macros, "w").write("\n".join(L) + "\n")
        print(f"wrote {args.macros}")
    return 0


def _rows(d, arm, ro):
    return {(r["ladder"], tuple(r["pair"])): r for r in d["pairs"].get(arm, {}).get(ro, [])}


def paired_ci(A_, B_, group, key_a="ok", key_b="ok", n=BOOT, seed=SEED):
    """Difference of satisfaction rates (A - B) on shared pairs, family-cluster bootstrap."""
    keys = [k for k in A_ if k in B_ and (group is None or A_[k]["type"] in group)]
    fam = defaultdict(list)
    for k in keys:
        fam[A_[k]["family"]].append((float(A_[k][key_a]), float(B_[k][key_b])))
    F = list(fam.values())
    point = sum(a - b for f in F for a, b in f) / sum(len(f) for f in F)
    rng = random.Random(seed)
    vals = []
    for _ in range(n):
        s = [rng.choice(F) for _ in F]
        tot = sum(len(f) for f in s)
        vals.append(sum(a - b for f in s for a, b in f) / tot)
    vals.sort()
    return point, vals[int(0.025 * n)], vals[int(0.975 * n) - 1], len(keys)


def cmd_paired(args):
    d = json.load(open(os.path.join(ROOT, "eval.json")))
    fair = json.load(open(os.path.join(ROOT, "fair_judges", "eval.json")))
    inc, inv = set(E.INCREASE), set(E.INVARIANCE)
    out = {}
    for arm, tag in (("graph_gpt6", "Gpt"), ("graph_gptoss", "Oss"), ("pair_gptoss", "PairOss"),
                     ("pair_llama", "PairLlama")):
        L, W = _rows(d, arm, "lambda"), _rows(d, arm, "wsum")
        Dd = _rows(d, arm, "dsum")
        out[f"LcsWsumInc{tag}"] = paired_ci(L, W, inc)
        if Dd:
            out[f"LcsDsumInc{tag}"] = paired_ci(L, Dd, inc)
    L = _rows(d, "graph_gpt6", "lambda")
    J = {(r["ladder"], tuple(r["pair"])): r for r in fair["pairs"]["pairwise_verdicts__gpt-6-sol"]}
    out["LcsPairVInc"] = paired_ci(L, J, inc)
    out["LcsPairVInv"] = paired_ci(L, J, inv)
    for k, v in out.items():
        print(k, tuple(round(x, 4) if isinstance(x, float) else x for x in v))
    if args.macros:
        Lm = ["% Generated by scripts/arr_phaseb.py paired -- do not edit by hand."]
        f = lambda x: f"\\ensuremath{{{100 * x:+.1f}}}"  # noqa: E731
        for k, (p, lo, hi, n) in out.items():
            Lm.append(f"\\newcommand{{\\pc{k}}}{{{f(p)}}}")
            Lm.append(f"\\newcommand{{\\pc{k}Lo}}{{{f(lo)}}}")
            Lm.append(f"\\newcommand{{\\pc{k}Hi}}{{{f(hi)}}}")
            Lm.append(f"\\newcommand{{\\pc{k}N}}{{{n}}}")
        open(args.macros, "w").write("\n".join(Lm) + "\n")
        print(f"wrote {args.macros}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["noise", "paired"])
    ap.add_argument("--macros", default=None)
    args = ap.parse_args()
    return {"noise": cmd_noise, "paired": cmd_paired}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
